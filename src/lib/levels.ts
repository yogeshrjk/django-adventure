/**
 * Deterministically picks between '/blue.png' and '/yellow.png' for a given chapter/level ID
 * to ensure SSR and client hydration consistency while maintaining a random distribution
 * across all chapters. If no ID is provided, randomly chooses one.
 */
export function getChapterMascot(levelId?: number): string {
  if (levelId === undefined || levelId === null || isNaN(levelId)) {
    return Math.random() < 0.5 ? "/blue.png" : "/yellow.png";
  }
  // Deterministic pseudo-random distribution per chapter to ensure SSR/hydration consistency
  // while appearing random across chapters (mix of blue and yellow)
  const hash = Math.sin((levelId + 1) * 12.9898 + 78.233) * 43758.5453;
  return (hash - Math.floor(hash)) < 0.5 ? "/blue.png" : "/yellow.png";
}
